// Lists everything in photos/ and writes photos.js, so adding a photo is just
// dropping a file into photos/ and pushing. Runs on every deploy. Node 20+.
import { readdir, writeFile } from "node:fs/promises";

const DIR = new URL("../photos/", import.meta.url);
const OUT = new URL("../photos.js", import.meta.url);

const files = (await readdir(DIR))
  .filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
  .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

const body = `// Generated by scripts/build-photos.mjs. Do not edit by hand.\nwindow.PHOTOS = ${JSON.stringify(
  files.map((f) => "photos/" + encodeURIComponent(f)),
  null,
  2
)};\n`;

await writeFile(OUT, body);
console.log(`Wrote ${files.length} photos to photos.js.`);
