// Pulls the current song list for Annyka's Suno playlist and writes songs.js.
// Runs daily from .github/workflows/deploy.yml. Node 20+, no dependencies.
//
// Songs play through Suno's official embed player (suno.com/embed/<id>), so all
// we need here is each song's id, title and length. The page uses the length to
// know when to move on, because the embed doesn't report when a song ends.
import { writeFile, readFile } from "node:fs/promises";

const PLAYLIST_ID = "d67195dd-8e44-4bff-9ba8-65f9503c0b8c"; // https://suno.com/s/HMYJaOluH7QalSNx
const API = `https://studio-api.prod.suno.com/api/playlist/${PLAYLIST_ID}/`;
const OUT = new URL("../songs.js", import.meta.url);

async function fetchPage(page) {
  const res = await fetch(`${API}?page=${page}`, { headers: { accept: "application/json" } });
  if (!res.ok) throw new Error(`Suno playlist page ${page}: HTTP ${res.status}`);
  return res.json();
}

function toSongs(pages) {
  const seen = new Set();
  const songs = [];
  for (const page of pages) {
    for (const entry of page.playlist_clips || []) {
      const clip = entry.clip || entry;
      if (!clip || !clip.id || seen.has(clip.id)) continue;
      if (clip.status && clip.status !== "complete") continue;
      if (clip.is_trashed) continue;
      const duration = Number(clip.duration || (clip.metadata && clip.metadata.duration)) || 0;
      seen.add(clip.id);
      songs.push({
        id: clip.id,
        title: (clip.title || "Untitled").trim(),
        duration: Math.round(duration),
        image: clip.image_large_url || clip.image_url || "",
      });
    }
  }
  return songs;
}

async function main() {
  const pages = [];
  for (let page = 1; page <= 20; page++) {
    const data = await fetchPage(page);
    if (!data.playlist_clips || data.playlist_clips.length === 0) break;
    pages.push(data);
  }
  const songs = toSongs(pages);
  if (songs.length === 0) {
    // Never wipe the TV's music because Suno had a bad day; keep the last good list.
    console.error("No songs returned; leaving songs.js unchanged.");
    process.exitCode = 1;
    return;
  }
  const album = { name: pages[0].name || "Annyka", image: pages[0].image_url || "" };
  const body =
    `// Generated by scripts/update-songs.mjs. Do not edit by hand.\n` +
    `window.ALBUM = ${JSON.stringify(album)};\n` +
    `window.SONGS = ${JSON.stringify(songs, null, 2)};\n`;
  const prev = await readFile(OUT, "utf8").catch(() => "");
  if (prev === body) {
    console.log(`No changes (${songs.length} songs).`);
    return;
  }
  await writeFile(OUT, body);
  console.log(`Wrote ${songs.length} songs to songs.js.`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
